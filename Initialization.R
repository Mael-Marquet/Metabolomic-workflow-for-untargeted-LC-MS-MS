get_path_gui <- function() {
  
  ui <- fluidPage(
    titlePanel("Select the Project Root Directory (exemple : C:/Users/EXT-PMarquet1/Test_16-02-26)"),
    
    sidebarLayout(
      sidebarPanel(
        textInput(
          inputId = "path",
          label = "Enter the folder path :",
          value = ""
        ),
        
        tags$div(
          class = "alert alert-info",
          style = "margin-top: 10px;",
          icon("circle-info"),
          strong(" The following files will be created in the root directory : "),
          "mzML, Results, Metadata, Rdata_checkpoint"
        ),
        
        actionButton("submit", "Submit", class = "btn-success")
      ),
      mainPanel(
        h4("What is a root directory ?"),
        p("A ", strong("root directory"), " (or root path) is the top-level folder of your project. 
          It serves as the common starting point from which all project files and subfolders are organized."),
        p("All working files and output folders generated by this application will be created 
          directly inside this directory. If the folder does not exist, it will be created automatically.")
      )
    )
  )
  
  server <- function(input, output, session) {
    
    # Return path when Submit is clicked
    
    observeEvent(input$submit, {
      
      if(nchar(trimws(input$path)) == 0){
        
        showNotification("Path cannot be empty.", type = "error")
        
        return(NULL)
        
      }
      
      stopApp(input$path)
    })
    
  }
  
  runApp(shinyApp(ui, server), launch.browser = TRUE)
