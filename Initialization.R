  # ── Server ─────────────────────────────────────────────────────────────
  server <- function(input, output, session) {
    
    sample_data <- reactive({
      
      req(input$file)
      ext <- tools::file_ext(input$file$name)
      
      if (ext %in% c("csv")) {
        
        df <- read.csv(input$file$datapath, stringsAsFactors = FALSE)
        
      } else if (ext %in% c("xlsx", "xls")) {
        
        df <- read_excel(input$file$datapath)
        
      } else {
        
        showNotification("Invalid file type. Please upload CSV or Excel.", type = "error")
        return(NULL)
      }
      
      # Check required columns
      
      required_columns <- c("SampleName", "SampleType", "Group", "OrderInjection",
                            "PairedID", "Longitudinal_TimePoint", "Batch", "Hypothesis_1")
      
      missing_columns <- setdiff(required_columns, colnames(df))
      
      if (length(missing_columns) > 0) {
        showNotification(
          paste0("Missing required column(s): ", paste(missing_columns, collapse = ", ")),
          type = "error"
        )
        return(NULL)
      }
      
      # Check SampleType validity
      
      valid_sample_types <- c("Bio", "pool_QC", "blank_analysis", "pool_Qcdil")
      
