  server <- function(input, output, session) {
    
    scan_files <- reactive({
      invalidateLater(1000, session)
      all_files  <- list.files(mzML_folder, full.names = FALSE)
      mzml_files <- all_files[grepl("\\.mzML$", all_files, ignore.case = TRUE)]
      list(n_mzml = length(mzml_files), n_non_mzml = length(setdiff(all_files, mzml_files)))
    })
    
    output$mzml_count <- renderUI({
      div(class = "count-box",
          h3(tags$span(class = "count-number", scan_files()$n_mzml),
             " mzML files detected in the mzML folder.")
      )
    })
    
    output$non_mzml_warning <- renderUI({
      if (scan_files()$n_non_mzml != 0)
        div(class = "warn-box",
            h3(tags$span("\u26a0", style = "color:#ffc107;"),
               tags$span(paste0(" ", scan_files()$n_non_mzml, " non-mzML files detected in the mzML folder."),
                         style = "color:#e65100; font-weight:bold;"))
        )
    })
    
    clicked <- reactiveVal(FALSE)
    output$checkbox_error <- renderUI({
      if (clicked() && !input$confirmed)
        tags$p("\u274c You must check the confirmation box before continuing.", 
               style = "color:red; font-weight:bold;")
    })
    observeEvent(input$continue, { clicked(TRUE); req(input$confirmed); stopApp(TRUE) })
  }
  
  runApp(shinyApp(ui, server), launch.browser = TRUE)
}

